using System;
using UnityEngine;

namespace Soup.Runtime.Blackboards
{
    /// <summary>
    /// One variable on a graph's blackboard. Variable types derive from ABlackboardElement&lt;T&gt;, never from this directly:
    /// <c>[Serializable] public sealed class Vector3BlackboardElement : ABlackboardElement&lt;Vector3&gt; { }</c>. One class per value
    /// type; the editor names it after the class, minus "BlackboardElement".
    /// </summary>
    [Serializable]
    public abstract class ABlackboardElement
    {
        [SerializeField, HideInInspector]
        private string m_id; // Generated by the editor when the element is added.

        [SerializeField]
        private string m_name;

        public string Id => m_id;
        public string Name => m_name;

        public abstract Type ValueType { get; }

        /// <summary>
        /// The value as an object, for code that doesn't know the type. Setting a value of the wrong type logs and keeps the old one.
        /// </summary>
        public abstract object BoxedValue { get; set; }

        // Only ABlackboardElement<T> can call this, so every element has a typed value.
        private protected ABlackboardElement()
        {
        }

#if UNITY_EDITOR
        internal void SetId(string id)
        {
            m_id = id;
        }

        internal void SetName(string name)
        {
            m_name = name;
        }

        internal const string IdFieldName = nameof(m_id);
        internal const string NameFieldName = nameof(m_name);
        internal const string ValueFieldName = "m_value"; // Declared by ABlackboardElement<T>.
#endif
    }

    [Serializable]
    public abstract class ABlackboardElement<T> : ABlackboardElement
    {
        [SerializeField]
        private T m_value;

        public T Value
        {
            get => m_value;
            set => m_value = value;
        }

        public sealed override Type ValueType => typeof(T);

        public sealed override object BoxedValue
        {
            get => m_value;
            set
            {
                if (value is T typedValue)
                {
                    m_value = typedValue;
                }
                else if (value == null && default(T) == null)
                {
                    m_value = default;
                }
                else
                {
                    Debug.LogError($"[Soup] Blackboard: '{Name}' holds a {typeof(T).Name}, so it can't be set to a {value?.GetType().Name ?? "null"}.");
                }
            }
        }
    }
}
