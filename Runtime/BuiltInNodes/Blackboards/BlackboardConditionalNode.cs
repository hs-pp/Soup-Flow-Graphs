using System;
using System.Collections.Generic;
using Soup.Runtime.Blackboards;
using UnityEngine;

namespace Soup.Runtime.BuiltInNodes.Blackboards
{
    /// <summary>
    /// Tests one blackboard variable against an ordered list of conditions, each with its own outport, and takes the first that
    /// holds. Else is taken when none does, and when the node has no variable or a condition of the wrong type (which also logs).
    /// </summary>
    [Serializable]
    [CustomNode(typeof(AFlowGraph), "Blackboard/Conditional")]
    public sealed class BlackboardConditionalNode : ANode
    {
        public const string ElsePort = "Else";

        [SerializeField]
        private BlackboardKey m_variable = new();

        [SerializeField]
        private List<BlackboardConditionalEntry> m_entries = new();

        public override void DefineOutports(List<OutportDefinition> outports)
        {
            foreach (BlackboardConditionalEntry entry in m_entries)
            {
                if (entry != null && !string.IsNullOrEmpty(entry.Id))
                {
                    outports.Add(new OutportDefinition(entry.Id, entry.Conditional?.GetLabel() ?? "(no condition)"));
                }
            }

            outports.Add(new OutportDefinition(ElsePort, ElsePort));
        }

        public override void OnNodeEnter(NodeExecutionContext context)
        {
            ABlackboardVariable variable = context.Blackboard?.GetVariable(m_variable);
            if (variable == null)
            {
                string reason = m_variable.IsSet ? $"no variable has the id '{m_variable.VariableId}'" : "no variable is picked";
                Debug.LogError($"[Soup] BlackboardConditionalNode ({Id}): {reason}. Taking Else.");
                context.TraverseEdge(ElsePort);
                return;
            }

            for (int i = 0; i < m_entries.Count; i++)
            {
                ABlackboardConditional conditional = m_entries[i]?.Conditional;
                if (conditional == null)
                {
                    Debug.LogError($"[Soup] BlackboardConditionalNode ({Id}): condition {i + 1} is empty, so it is skipped.");
                    continue;
                }

                if (!conditional.TryEvaluate(variable, out bool isTrue))
                {
                    Debug.LogError($"[Soup] BlackboardConditionalNode ({Id}): condition {i + 1} works on {conditional.ValueType.Name}, but '{variable.Name}' holds a {variable.ValueType.Name}. Taking Else.");
                    context.TraverseEdge(ElsePort);
                    return;
                }

                if (isTrue)
                {
                    context.TraverseEdge(m_entries[i].Id);
                    return;
                }
            }

            context.TraverseEdge(ElsePort);
        }

#if UNITY_EDITOR
        internal const string VariableFieldName = nameof(m_variable);
        internal const string EntriesFieldName = nameof(m_entries);
#endif
    }

    /// <summary>
    /// One condition and the id of the outport it leads to.
    /// </summary>
    [Serializable]
    public sealed class BlackboardConditionalEntry
    {
        [SerializeField, HideInInspector]
        private string m_id; // The outport id. Generated by the editor when the entry is added.

        [SerializeReference]
        private ABlackboardConditional m_conditional;

        public string Id => m_id;
        public ABlackboardConditional Conditional => m_conditional;

#if UNITY_EDITOR
        internal const string IdFieldName = nameof(m_id);
        internal const string ConditionalFieldName = nameof(m_conditional);
#endif
    }
}
