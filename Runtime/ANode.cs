using System;
using System.Collections.Generic;
using System.Reflection;
using UnityEngine;

namespace Soup.Runtime
{
    /// <summary>
    /// TODO: Should track some sort of "bool IsNonComputeNode" so we can skip them in Graph update loop. (dont waste a frame transitioning through them)
    /// </summary>
    [Serializable]
    public abstract class ANode
    {
        private static readonly Dictionary<Type, string[]> s_staticOutportNames = new(); // TODO: Move this out to a helper function.

        [SerializeField, HideInInspector]
        protected string m_id; // Generated by the editor when the node is created.
        public string Id => m_id;

        [SerializeField, HideInInspector]
        private List<OutportEdge> m_outports = new (0);

        public virtual NodeRuntimeState CreateRuntimeState() { return new DefaultNodeRuntimeState(); }
        public virtual void OnNodeEnter(NodeExecutionContext context) { }
        public virtual void OnNodeUpdate(NodeExecutionContext context) { }
        public virtual void OnNodeExit(NodeExecutionContext context) { }

#region Outports
        public virtual void DefineOutports(List<OutportDefinition> outports)
        {
            string[] names = GetStaticOutportNames(GetType());
            for (int i = 0; i < names.Length; i++)
            {
                outports.Add(new OutportDefinition(names[i], names[i]));
            }
        }
        
        public OutportEdge GetOutportEdge(string outportId)
        {
            if (string.IsNullOrEmpty(outportId))
            {
                return null;
            }

            return m_outports.Find(o => o != null && o.Id == outportId);
        }

        private static string[] GetStaticOutportNames(Type nodeType)
        {
            if (s_staticOutportNames.TryGetValue(nodeType, out string[] names))
            {
                return names;
            }

            OutportsAttribute attribute = nodeType.GetCustomAttribute<OutportsAttribute>(inherit: true);
            if (attribute == null)
            {
                names = new[] { "Out" };
            }
            else
            {
                names = new string[attribute.Names.Count];
                for (int i = 0; i < names.Length; i++)
                {
                    names[i] = attribute.Names[i];
                }
            }

            s_staticOutportNames[nodeType] = names;
            return names;
        }
#endregion

#if UNITY_EDITOR
        internal void SetId(string id)
        {
            m_id = id;
        }
        
        internal List<OutportEdge> Outports => m_outports;

        internal const string IdFieldName = nameof(m_id);
        internal const string OutportsFieldName = nameof(m_outports);
#endif
    }
}
